import React, { useMemo, useState } from 'react';
import {
  Copy,
  Check,
  FileSpreadsheet,
  X,
  Layers,
} from 'lucide-react';
import { useCanvasStore } from '../../store/useCanvasStore';
import { AnimatedPopover } from '../ui/AnimatedPopover';
import { getAWSCategoryColor } from '../../utils/awsCategoryColors';
import { useCompassStore } from '../../store/useCompassStore';

export interface CanvasBomPopoverProps {
  isOpen: boolean;
  onClose: () => void;
  triggerRef: React.RefObject<HTMLButtonElement | null>;
}

export const CanvasBomPopover: React.FC<CanvasBomPopoverProps> = ({
  isOpen,
  onClose,
  triggerRef,
}) => {
  const nodes = useCanvasStore((s) => s.nodes);
  const edges = useCanvasStore((s) => s.edges);
  const activeDiagramName = useCanvasStore((s) => s.activeDiagramName);
  const theme = useCompassStore((s) => s.theme);
  const [copied, setCopied] = useState(false);

  // Separate service nodes, boundary containers, and external actors
  const { serviceNodes, boundaryNodes, actorNodes } = useMemo(() => {
    const services = nodes.filter((n) => !n.data?.isBoundary && !n.data?.isAnnotation && !n.data?.isExternalActor);
    const boundaries = nodes.filter((n) => n.data?.isBoundary);
    const actors = nodes.filter((n) => n.data?.isExternalActor);
    return { serviceNodes: services, boundaryNodes: boundaries, actorNodes: actors };
  }, [nodes]);

  // Group service nodes by AWS category
  const servicesByCategory = useMemo(() => {
    const map = new Map<string, typeof serviceNodes>();
    serviceNodes.forEach((node) => {
      const cat = node.data?.category || 'Compute';
      const existing = map.get(cat) || [];
      existing.push(node);
      map.set(cat, existing);
    });
    return Array.from(map.entries()).sort((a, b) => b[1].length - a[1].length);
  }, [serviceNodes]);

  // Markdown representation of the Bill of Materials
  const markdownBom = useMemo(() => {
    const lines: string[] = [
      `# Architecture Bill of Materials: ${activeDiagramName}`,
      `*Generated by AWS Compass Architecture Studio on ${new Date().toLocaleDateString()}*`,
      '',
      `## Executive Summary`,
      `- **Total AWS Services**: ${serviceNodes.length}`,
      `- **Group Boundaries**: ${boundaryNodes.length}`,
      `- **External Actors / Clients**: ${actorNodes.length}`,
      `- **Inter-Service Data Flows**: ${edges.length}`,
      '',
      `## Service Manifest`,
      `| # | Category | Resource / Service | AWS Identifier | Tier | Environment | Role / Notes |`,
      `|---|---|---|---|---|---|---|`,
    ];

    let index = 1;
    servicesByCategory.forEach(([category, catNodes]) => {
      catNodes.forEach((n) => {
        const title = n.data?.customTitle || n.data?.label || 'Service';
        const svcId = n.data?.serviceId || '';
        const tier = n.data?.tier ? `Tier ${n.data.tier}` : 'Tier 1';
        const env = n.data?.env || 'Prod';
        const role = (n.data?.roleSubtitle || n.data?.customNotes || '').replace(/\|/g, '-');
        lines.push(`| ${index++} | ${category} | ${title} | \`${svcId}\` | ${tier} | ${env} | ${role} |`);
      });
    });

    if (boundaryNodes.length > 0) {
      lines.push('');
      lines.push(`## Infrastructure Containers & Boundaries`);
      lines.push(`| # | Boundary Type | Boundary Label | CIDR Block | Contained Resources |`);
      lines.push(`|---|---|---|---|---|`);

      boundaryNodes.forEach((b, idx) => {
        const bType = b.data?.boundaryType || 'boundary';
        const bLabel = b.data?.boundaryLabel || b.data?.label || 'Boundary';
        const cidr = b.data?.cidr || '-';
        const containedCount = nodes.filter((n) => n.parentId === b.id).length;
        lines.push(`| ${idx + 1} | ${bType} | ${bLabel} | ${cidr} | ${containedCount} |`);
      });
    }

    if (edges.length > 0) {
      lines.push('');
      lines.push(`## Inter-Service Protocol & Data Flow`);
      lines.push(`| # | Source Component | Protocol / Direction | Target Component |`);
      lines.push(`|---|---|---|---|`);

      edges.forEach((e, idx) => {
        const srcNode = nodes.find((n) => n.id === e.source);
        const tgtNode = nodes.find((n) => n.id === e.target);
        const srcTitle = srcNode?.data?.customTitle || srcNode?.data?.label || e.source;
        const tgtTitle = tgtNode?.data?.customTitle || tgtNode?.data?.label || e.target;
        const proto = e.data?.customLabel || e.protocol || 'HTTPS/REST';
        lines.push(`| ${idx + 1} | ${srcTitle} | \`${proto}\` | ${tgtTitle} |`);
      });
    }

    return lines.join('\n');
  }, [activeDiagramName, serviceNodes, boundaryNodes, actorNodes, edges, servicesByCategory, nodes]);

  const handleCopyMarkdown = async () => {
    try {
      await navigator.clipboard.writeText(markdownBom);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Fallback
    }
  };

  return (
    <AnimatedPopover
      isOpen={isOpen}
      onClose={onClose}
      triggerRef={triggerRef}
      align="right"
      className="p-0 overflow-hidden w-[420px] shadow-2xl"
    >
      <div
        style={{
          backgroundColor: 'var(--aws-popover-bg)',
          borderColor: 'var(--aws-border)',
        }}
        className="flex flex-col max-h-[520px] select-none text-[12px]"
      >
        {/* Header Bar */}
        <div
          style={{
            backgroundColor: 'var(--aws-card-bg)',
            borderBottomColor: 'var(--aws-border)',
          }}
          className="px-4 py-2.5 border-b flex items-center justify-between"
        >
          <div className="flex items-center gap-2">
            <FileSpreadsheet className="w-4 h-4 text-[#FF9900]" />
            <div>
              <span
                style={{ color: 'var(--aws-text-primary)' }}
                className="font-bold text-[13px] block leading-tight"
              >
                Bill of Materials (BOM)
              </span>
              <span className="text-[10px] text-[var(--aws-text-muted)] font-mono">
                {activeDiagramName}
              </span>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleCopyMarkdown}
              className={`flex items-center gap-1.5 px-2.5 py-1 rounded-[4px] border text-[11px] font-semibold transition-all cursor-pointer ${copied
                  ? 'bg-[#1D8102]/15 text-[#38D9A9] border-[#1D8102]/40'
                  : 'bg-[var(--aws-card-bg)] text-[var(--aws-text-primary)] border-[var(--aws-border)] hover:border-[#FF9900] hover:text-[#FF9900]'
                }`}
              title="Copy Bill of Materials as Markdown table"
            >
              {copied ? (
                <>
                  <Check className="w-3 h-3 text-[#38D9A9]" />
                  <span>Copied</span>
                </>
              ) : (
                <>
                  <Copy className="w-3 h-3" />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>

            <button
              type="button"
              onClick={onClose}
              className="p-1 rounded-[4px] text-[var(--aws-text-muted)] hover:text-[var(--aws-text-primary)] hover:bg-[var(--aws-page-bg)] transition-colors cursor-pointer"
              title="Close"
              aria-label="Close"
            >
              <X className="w-3.5 h-3.5" />
            </button>
          </div>
        </div>

        {/* Stats Strip */}
        <div
          style={{
            backgroundColor: 'var(--aws-page-bg)',
            borderBottomColor: 'var(--aws-border)',
          }}
          className="px-4 py-2 border-b grid grid-cols-4 gap-2 text-center text-[11px]"
        >
          <div>
            <span className="block text-[var(--aws-text-muted)] text-[10px]">Services</span>
            <span
              style={{ color: 'var(--aws-text-primary)' }}
              className="font-bold font-mono text-[13px]"
            >
              {serviceNodes.length}
            </span>
          </div>
          <div>
            <span className="block text-[var(--aws-text-muted)] text-[10px]">Boundaries</span>
            <span
              style={{ color: 'var(--aws-text-primary)' }}
              className="font-bold font-mono text-[13px]"
            >
              {boundaryNodes.length}
            </span>
          </div>
          <div>
            <span className="block text-[var(--aws-text-muted)] text-[10px]">Actors</span>
            <span
              style={{ color: 'var(--aws-text-primary)' }}
              className="font-bold font-mono text-[13px]"
            >
              {actorNodes.length}
            </span>
          </div>
          <div>
            <span className="block text-[var(--aws-text-muted)] text-[10px]">Connections</span>
            <span
              style={{ color: 'var(--aws-text-primary)' }}
              className="font-bold font-mono text-[13px]"
            >
              {edges.length}
            </span>
          </div>
        </div>

        {/* Body Breakdown List */}
        <div className="flex-1 overflow-y-auto p-4 space-y-4 custom-scrollbar">
          {/* Services by Category */}
          {servicesByCategory.length > 0 ? (
            <div>
              <span className="text-[10px] font-bold uppercase tracking-wider text-[var(--aws-text-muted)] block mb-2">
                Services by Category
              </span>
              <div className="space-y-3">
                {servicesByCategory.map(([category, catNodes]) => {
                  const catColor = getAWSCategoryColor(category, theme);
                  return (
                    <div
                      key={category}
                      style={{
                        backgroundColor: 'var(--aws-page-bg)',
                        borderColor: 'var(--aws-border)',
                      }}
                      className="rounded-[6px] border p-2.5"
                    >
                      <div className="flex items-center justify-between pb-1.5 mb-1.5 border-b border-[var(--aws-border)]">
                        <div className="flex items-center gap-1.5">
                          <span
                            className="w-2 h-2 rounded-full"
                            style={{ backgroundColor: catColor }}
                            aria-hidden="true"
                          />
                          <span
                            style={{ color: 'var(--aws-text-primary)' }}
                            className="font-semibold text-[12px]"
                          >
                            {category}
                          </span>
                        </div>
                        <span className="font-mono text-[10px] text-[var(--aws-text-muted)]">
                          {catNodes.length} {catNodes.length === 1 ? 'service' : 'services'}
                        </span>
                      </div>

                      <div className="space-y-1">
                        {catNodes.map((n) => (
                          <div
                            key={n.id}
                            className="flex items-center justify-between text-[11px] py-0.5"
                          >
                            <span
                              style={{ color: 'var(--aws-text-primary)' }}
                              className="truncate pr-2"
                            >
                              {n.data?.customTitle || n.data?.label}
                            </span>
                            <div className="flex items-center gap-1.5 shrink-0">
                              <span
                                className={`text-[9px] font-mono px-1 py-0.2 rounded border ${n.data?.tier === 1
                                    ? 'bg-[#FF9900]/10 text-[#FF9900] border-[#FF9900]/25'
                                    : 'bg-[#545B64]/10 text-[var(--aws-text-muted)] border-[var(--aws-border)]'
                                  }`}
                              >
                                T{n.data?.tier || 1}
                              </span>
                              <span className="font-mono text-[10px] text-[var(--aws-text-muted)]">
                                {n.data?.env || 'Prod'}
                              </span>
                            </div>
                          </div>
                        ))}
                      </div>
                    </div>
                  );
                })}
              </div>
            </div>
          ) : (
            <div className="p-4 text-center text-[var(--aws-text-muted)] text-[12px]">
              No AWS service nodes placed on canvas yet.
            </div>
          )}

          {/* Group Boundaries List */}
          {boundaryNodes.length > 0 && (
            <div>
              <span className="text-[10px] font-bold uppercase tracking-wider text-[var(--aws-text-muted)] block mb-2">
                Infrastructure Boundaries
              </span>
              <div className="space-y-1.5">
                {boundaryNodes.map((b) => (
                  <div
                    key={b.id}
                    style={{
                      backgroundColor: 'var(--aws-page-bg)',
                      borderColor: 'var(--aws-border)',
                    }}
                    className="rounded-[4px] border px-2.5 py-1.5 flex items-center justify-between text-[11px]"
                  >
                    <div className="flex items-center gap-2 truncate">
                      <Layers className="w-3.5 h-3.5 text-[#8C4FFF] shrink-0" />
                      <span
                        style={{ color: 'var(--aws-text-primary)' }}
                        className="truncate font-medium"
                      >
                        {b.data?.boundaryLabel || b.data?.label}
                      </span>
                    </div>
                    {b.data?.cidr && (
                      <span className="font-mono text-[10px] text-[var(--aws-text-muted)] shrink-0">
                        {b.data.cidr}
                      </span>
                    )}
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      </div>
    </AnimatedPopover>
  );
};

export default CanvasBomPopover;